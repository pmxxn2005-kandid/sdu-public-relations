CREATE TABLE IF NOT EXISTS users (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(250) NOT NULL, email VARCHAR(250) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, role VARCHAR(20) NOT NULL DEFAULT 'author', active TINYINT NOT NULL DEFAULT 1, created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS categories (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(250) NOT NULL UNIQUE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS media (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(250) NOT NULL, path VARCHAR(250) NOT NULL,
 mime VARCHAR(100) NOT NULL, size BIGINT NOT NULL, alt VARCHAR(500) NOT NULL DEFAULT '', uploaded_by BIGINT UNSIGNED NULL,
 created_at DATETIME NOT NULL, FOREIGN KEY (uploaded_by) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS contents (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, type VARCHAR(20) NOT NULL, title VARCHAR(250) NOT NULL, slug VARCHAR(190) NOT NULL UNIQUE,
 excerpt TEXT NOT NULL, body LONGTEXT NOT NULL, status VARCHAR(20) NOT NULL DEFAULT 'draft',
 category_id BIGINT UNSIGNED NULL, cover_id BIGINT UNSIGNED NULL, author_id BIGINT UNSIGNED NULL,
 tags VARCHAR(500) NOT NULL DEFAULT '', published_at DATETIME NULL, starts_at DATETIME NULL, ends_at DATETIME NULL,
 location VARCHAR(500) NOT NULL DEFAULT '', event_status VARCHAR(20) NOT NULL DEFAULT 'normal', external_url TEXT NOT NULL,
 seo_title VARCHAR(250) NOT NULL DEFAULT '', seo_description VARCHAR(500) NOT NULL DEFAULT '',
 version INT NOT NULL DEFAULT 1, created_at DATETIME NOT NULL, updated_at DATETIME NOT NULL,
 FOREIGN KEY (category_id) REFERENCES categories(id) ON DELETE SET NULL,
 FOREIGN KEY (cover_id) REFERENCES media(id) ON DELETE SET NULL,
 FOREIGN KEY (author_id) REFERENCES users(id) ON DELETE SET NULL,
 INDEX content_public (type, status, published_at), INDEX event_dates (starts_at, ends_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS content_media (
 content_id BIGINT UNSIGNED NOT NULL, media_id BIGINT UNSIGNED NOT NULL, sort_order INT NOT NULL DEFAULT 0,
 PRIMARY KEY(content_id, media_id), FOREIGN KEY (content_id) REFERENCES contents(id) ON DELETE CASCADE,
 FOREIGN KEY (media_id) REFERENCES media(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS personnel (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, name VARCHAR(250) NOT NULL, position VARCHAR(250) NOT NULL,
 department VARCHAR(250) NOT NULL DEFAULT '', photo_id BIGINT UNSIGNED NULL, sort_order INT NOT NULL DEFAULT 0,
 published TINYINT NOT NULL DEFAULT 0, created_at DATETIME NOT NULL, updated_at DATETIME NOT NULL,
 FOREIGN KEY (photo_id) REFERENCES media(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS settings (name VARCHAR(100) PRIMARY KEY, value TEXT NOT NULL) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS revisions (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, content_id BIGINT UNSIGNED NOT NULL, user_id BIGINT UNSIGNED NULL,
 snapshot LONGTEXT NOT NULL, created_at DATETIME NOT NULL,
 FOREIGN KEY (content_id) REFERENCES contents(id) ON DELETE CASCADE, FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS audit_logs (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id BIGINT UNSIGNED NULL, action VARCHAR(50) NOT NULL,
 entity VARCHAR(50) NOT NULL, entity_id BIGINT NOT NULL, details TEXT NOT NULL, created_at DATETIME NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS login_attempts (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, identifier VARCHAR(64) NOT NULL, created_at DATETIME NOT NULL,
 INDEX login_limit (identifier, created_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS slug_redirects (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY, old_slug VARCHAR(190) NOT NULL, content_id BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY (content_id) REFERENCES contents(id) ON DELETE CASCADE, INDEX redirects_slug (old_slug)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS media_folders (
 id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(250) NOT NULL,
 created_at DATETIME NOT NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
CREATE TABLE IF NOT EXISTS media_folder_items (
 media_id BIGINT UNSIGNED PRIMARY KEY,
 folder_id BIGINT UNSIGNED NOT NULL,
 FOREIGN KEY (media_id) REFERENCES media(id) ON DELETE CASCADE,
 FOREIGN KEY (folder_id) REFERENCES media_folders(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
